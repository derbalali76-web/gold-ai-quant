class Msg(str):
    """Arabic text plus the code/arguments it was rendered from."""
    code: str
    args: tuple

    def __new__(cls, code: str, args: tuple, text: str):
        o = super().__new__(cls, text)
        o.code, o.args = code, tuple(args)
        return o

    def __reduce__(self):
        return (Msg, (self.code, self.args, str(self)))

    def __copy__(self):
        return self

    def __deepcopy__(self, memo):
        return self


def M(code: str, *args: Any) -> Msg:
    """Build a message. Args are strings/ints (pre-formatted) or nested Msg."""
    text = CATALOG_AR[code].format(*[str(a) for a in args])
    return Msg(code, args, text)


def ref_dict(x: Any) -> dict:
    """JSON-ready reference: {code, args, text_ar}. Plain strings become code 'raw' (shown as-is)."""
    if isinstance(x, Msg):
        return {"code": x.code, "args": [ref_dict(a) if isinstance(a, Msg) else str(a) for a in x.args], "text_ar": str(x)}
    return {"code": "raw", "args": [], "text_ar": str(x)}


def cut_short(text: str) -> str:
    """First clause of a rejection reason (used in 'we wait because ...')."""
    return text.split("؛")[0].split(" — ")[0].rstrip(".")
